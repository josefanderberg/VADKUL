export function filterSources(opts: { id?: string; region?: string; engine?: string; verified?: string; ids?: string[] }): Source[] {
    return SOURCES.filter((s) => {
        if (opts.id && !s.id.includes(opts.id)) return false;
        if (opts.ids && !opts.ids.includes(s.id)) return false;   // exakt id-lista
        if (opts.region && s.region !== opts.region) return false;
        if (opts.engine && s.engine !== opts.engine) return false;
        if (opts.verified && s.lastVerified !== opts.verified) return false;
        return true;
    });
}
